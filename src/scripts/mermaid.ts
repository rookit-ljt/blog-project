/**
 * Client-side Mermaid.js rendering with dynamic loading and theme support.
 */

let isRendering = false;
let renderQueue = false;
let idCounter = 0;

function getIsDark(): boolean {
  const root = document.documentElement;
  return (
    root.classList.contains("dark") ||
    root.getAttribute("data-theme") === "dark" ||
    document.firstElementChild?.getAttribute("data-theme") === "dark"
  );
}

export async function renderMermaidDiagrams() {
  // 1. Find unrendered mermaid pre blocks
  const rawElements = Array.from(
    document.querySelectorAll<HTMLElement>(
      "pre[data-language='mermaid'], pre:has(> code.language-mermaid), pre.mermaid"
    )
  );

  const preElements = rawElements.map(el =>
    el.tagName.toLowerCase() === "code" ? el.parentElement! : el
  );
  const uniquePreElements = Array.from(new Set(preElements)).filter(
    el => !el.closest(".mermaid-container")
  );

  // 2. Find already rendered containers (for theme toggling)
  const existingContainers = Array.from(
    document.querySelectorAll<HTMLElement>(
      ".mermaid-container[data-mermaid-code]"
    )
  );

  if (uniquePreElements.length === 0 && existingContainers.length === 0) {
    return;
  }

  if (isRendering) {
    renderQueue = true;
    return;
  }
  isRendering = true;

  try {
    const { default: mermaid } = await import("mermaid");

    const isDark = getIsDark();
    mermaid.initialize({
      startOnLoad: false,
      theme: isDark ? "dark" : "default",
      themeVariables: isDark
        ? {
            darkMode: true,
            background: "#0d1117",
            primaryColor: "#2563eb",
            primaryTextColor: "#f1f5f9",
            lineColor: "#94a3b8",
            secondaryColor: "#1e293b",
            tertiaryColor: "#0f172a",
          }
        : {
            background: "#ffffff",
            primaryColor: "#3b82f6",
            primaryTextColor: "#1e293b",
            lineColor: "#64748b",
          },
      securityLevel: "loose",
      fontFamily: "inherit",
    });

    // Process new pre elements
    for (const pre of uniquePreElements) {
      const code = (
        pre.querySelector("code")?.textContent ||
        pre.textContent ||
        ""
      ).trim();
      if (!code) continue;

      const container = document.createElement("div");
      container.className =
        "mermaid-container my-6 flex justify-center overflow-x-auto rounded-lg border border-border bg-card p-4 text-center [&>svg]:max-w-full [&>svg]:h-auto";
      container.dataset.mermaidCode = code;

      const uniqueId = `mermaid-svg-${Date.now()}-${idCounter++}`;

      try {
        const { svg, bindFunctions } = await mermaid.render(uniqueId, code);
        container.innerHTML = svg;
        if (typeof bindFunctions === "function") {
          bindFunctions(container);
        }
        pre.parentNode?.replaceChild(container, pre);
      } catch (err) {
        console.error("Mermaid render error:", err);
        // Clean up any leaked error element generated by mermaid
        document.getElementById(`d${uniqueId}`)?.remove();
        document.getElementById(uniqueId)?.remove();
      }
    }

    // Re-render existing containers if theme changed
    for (const container of existingContainers) {
      const code = container.dataset.mermaidCode;
      if (!code) continue;

      const uniqueId = `mermaid-svg-${Date.now()}-${idCounter++}`;
      try {
        const { svg, bindFunctions } = await mermaid.render(uniqueId, code);
        container.innerHTML = svg;
        if (typeof bindFunctions === "function") {
          bindFunctions(container);
        }
      } catch (err) {
        console.error("Mermaid re-render error:", err);
        document.getElementById(`d${uniqueId}`)?.remove();
        document.getElementById(uniqueId)?.remove();
      }
    }
  } catch (err) {
    console.error("Failed to load or execute Mermaid:", err);
  } finally {
    isRendering = false;
    if (renderQueue) {
      renderQueue = false;
      renderMermaidDiagrams();
    }
  }
}

let lastThemeIsDark = getIsDark();

function setupThemeObserver() {
  const root = document.documentElement;
  const observer = new MutationObserver(() => {
    const currentIsDark = getIsDark();
    if (currentIsDark !== lastThemeIsDark) {
      lastThemeIsDark = currentIsDark;
      renderMermaidDiagrams();
    }
  });

  observer.observe(root, {
    attributes: true,
    attributeFilter: ["data-theme", "class"],
  });
}

// Initial setup
if (typeof window !== "undefined") {
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => {
      renderMermaidDiagrams();
    });
  } else {
    renderMermaidDiagrams();
  }

  setupThemeObserver();

  // Re-run after View Transitions navigation
  document.addEventListener("astro:after-swap", () => {
    lastThemeIsDark = getIsDark();
    renderMermaidDiagrams();
  });
}
